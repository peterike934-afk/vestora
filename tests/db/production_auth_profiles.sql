-- Exact Production function sources.
CREATE OR REPLACE FUNCTION public.generate_referral_code()
 RETURNS text
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare
  code text;
  code_exists boolean;
begin
  loop
    code := upper(substring(md5(random()::text) from 1 for 8));
    select exists(select 1 from profiles where referral_code = code) into code_exists;
    exit when not code_exists;
  end loop;
  return code;
end;
$function$
;
CREATE OR REPLACE FUNCTION public.set_referral_code()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
begin
  if new.referral_code is null then
    new.referral_code := public.generate_referral_code();
  end if;
  return new;
end;
$function$
;
CREATE OR REPLACE FUNCTION public.protect_privileged_profile_columns()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  if tg_op = 'UPDATE' and not public.is_admin() then
    new.role := old.role;
    new.status := old.status;
  end if;
  return new;
end;
$function$
;
CREATE OR REPLACE FUNCTION public.handle_new_user()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
begin
  insert into public.profiles (id, email, full_name)
  values (new.id, new.email, new.raw_user_meta_data->>'full_name');
  return new;
end;
$function$
;
CREATE OR REPLACE FUNCTION public.apply_referral_code(p_referral_code text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_referrer_id uuid;
  v_referrer_bonus numeric;
  v_referred_bonus numeric;
  v_program_enabled boolean;
begin
  if exists (select 1 from profiles where id = auth.uid() and referred_by is not null) then
    return;
  end if;

  select referral_program_enabled, referral_referrer_bonus_usd, referral_referred_bonus_usd
  into v_program_enabled, v_referrer_bonus, v_referred_bonus
  from settings where id = true;

  if not v_program_enabled then
    return;
  end if;

  select id into v_referrer_id from profiles
  where referral_code = upper(trim(p_referral_code)) and id != auth.uid();

  if v_referrer_id is null then
    return;
  end if;

  update profiles set referred_by = v_referrer_id where id = auth.uid();

  insert into referrals (referrer_id, referred_id, referrer_bonus_usd, referred_bonus_usd, status)
  values (v_referrer_id, auth.uid(), v_referrer_bonus, v_referred_bonus, 'pending');
end;
$function$
;
CREATE OR REPLACE FUNCTION public.get_my_referrals()
 RETURNS TABLE(id bigint, referred_name text, status text, referrer_bonus_usd numeric, created_at timestamp with time zone, paid_at timestamp with time zone)
 LANGUAGE sql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  select r.id, p.full_name, r.status, r.referrer_bonus_usd, r.created_at, r.paid_at
  from referrals r
  join profiles p on p.id = r.referred_id
  where r.referrer_id = auth.uid()
  order by r.created_at desc;
$function$
;

create trigger trg_set_referral_code before insert on public.profiles
  for each row execute function public.set_referral_code();
create trigger protect_profile_privilege_escalation before update on public.profiles
  for each row execute function public.protect_privileged_profile_columns();
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- Production ACLs of the two referral functions (executable by everyone).
grant execute on function public.apply_referral_code(text), public.get_my_referrals() to anon, authenticated, service_role;

